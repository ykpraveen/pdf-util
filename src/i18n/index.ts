const storedLocale = typeof localStorage === 'undefined' ? null : localStorage.getItem('paperwork-locale')
const locale = ref<Locale>(storedLocale === 'de' ? 'de' : 'en')

function setLocale(nextLocale: Locale): void {
  locale.value = nextLocale
  localStorage?.setItem('paperwork-locale', nextLocale)
}

function resolveMessage(key: string, params: Record<string, string | number>): string {
  const raw = [messages[locale.value][key], messages.en[key], key].find(Boolean) as string
  const index = Number(Number(params.count ?? 1) !== 1)
  return raw.split('|')[index] ?? raw
}

function interpolateMessage(message: string, params: Record<string, string | number>): string {
  return message.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`))
}

export function useI18n() {
  const languageName = computed(() => locale.value === 'en' ? messages[locale.value]['language.german'] : messages[locale.value]['language.english'])
  function t(key: string, params: Record<string, string | number> = {}): string {
    return interpolateMessage(resolveMessage(key, params), params)
  }
  return { locale, languageName, setLocale, t }
}
